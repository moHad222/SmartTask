# =========================================================
# SPECIAL CASES
# =========================================================

# بعضی عبارت‌ها عمداً اولویت بالاتری دارند،
# چون در دیتاست هم همین معنا را دارند.

SPECIAL_RULES = [

    # خرید + دانشگاه → خرید
    ("خرید", "دانشگاه", "خرید"),

    # خرید + ورزش → خرید
    ("خرید", "ورزش", "خرید"),

    # خرید + درسی → خرید
    ("خرید", "درسی", "خرید"),

    # پرداخت + دانشگاه → مالی
    ("پرداخت", "دانشگاه", "مالی"),

    # پرداخت + باشگاه → مالی
    ("پرداخت", "باشگاه", "مالی"),

    # پروژه + کدنویسی/پایتون → برنامه نویسی
    ("پروژه", "پایتون", "برنامه نویسی"),

    ("پروژه", "کدنویسی", "برنامه نویسی"),

    ("پروژه", "برنامه نویسی", "برنامه نویسی"),
]


def apply_special_rules(text):

    for first, second, category in SPECIAL_RULES:

        if first in text and second in text:
            return category

    return None


# =========================================================
# KEYWORD SCORE
# =========================================================

def calculate_keyword_scores(text):

    scores = {
        category: 0
        for category in CATEGORIES
    }

    for category, keywords in CATEGORY_KEYWORDS.items():

        for keyword, weight in keywords:

            keyword = normalize_text(keyword)

            if keyword in text:
                scores[category] += weight

    return scores


# =========================================================
# PREDICT
# =========================================================

def predict_category(title):

    text = normalize_text(title)

    if not text:
        return "تعیین نشده"

    # -----------------------------------------------------
    # Special rules
    # -----------------------------------------------------

    special_category = apply_special_rules(text)

    if special_category:
        return special_category

    # -----------------------------------------------------
    # Load ML model
    # -----------------------------------------------------

    load_model()

    # -----------------------------------------------------
    # Keyword scores
    # -----------------------------------------------------

    keyword_scores = calculate_keyword_scores(text)

    best_keyword_category = max(
        keyword_scores,
        key=keyword_scores.get
    )

    best_keyword_score = keyword_scores[
        best_keyword_category
    ]

    # -----------------------------------------------------
    # ML prediction
    # -----------------------------------------------------

    vector = _vectorizer.transform(
        [text]
    )

    probabilities = _model.predict_proba(
        vector
    )[0]

    best_index = probabilities.argmax()

    ml_confidence = probabilities[
        best_index
    ]

    ml_category = _model.classes_[
        best_index
    ]

    # -----------------------------------------------------
    # Combine ML + Keywords
    # -----------------------------------------------------

    # اگر عبارت تخصصی و واضح باشد،
    # Keyword می‌تواند ML را اصلاح کند.

    if best_keyword_score >= 5:
        return best_keyword_category

    # اگر Keyword ضعیف است، به ML اعتماد می‌کنیم.

    if ml_confidence >= 0.45:

        if ml_category in CATEGORIES:
            return ml_category

    # اگر ML اطمینان زیادی ندارد ولی Keyword
    # حداقل نشانه‌ای دارد، از Keyword استفاده می‌کنیم.

    if best_keyword_score >= 3:
        return best_keyword_category

    # -----------------------------------------------------
    # Low confidence
    # -----------------------------------------------------

    if (
        ml_category in CATEGORIES
        and ml_confidence >= 0.30
    ):
        return ml_category

    return "تعیین نشده"